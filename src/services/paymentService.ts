import { supabase } from '../lib/supabase';
import type {
  Payment,
  PaymentMethod,
  RecordPaymentFormData,
  StudentFeeSummary,
  MonthlyFee,
} from '../types';
import { calculateFeeBalance, getFeeStatus, calculateDaysOverdue } from '../utils/feeUtils';

export interface PaymentHistoryFilterOptions {
  studentId?: string;
  batchId?: string;
  method?: PaymentMethod;
  startDate?: string;
  endDate?: string;
  search?: string;
  limit?: number;
}

/**
 * Checks if a duplicate payment was recorded in the last 60 seconds for the same
 * student, amount, and payment date.
 */
export async function checkRecentDuplicatePayment(
  studentId: string,
  amount: number,
  paymentDate: string
): Promise<{ isDuplicate: boolean; recentPayment?: Payment; error: string | null }> {
  try {
    const sixtySecondsAgo = new Date(Date.now() - 60 * 1000).toISOString();

    const { data, error } = await supabase
      .from('payments')
      .select('*')
      .eq('student_id', studentId)
      .eq('amount', amount)
      .eq('payment_date', paymentDate)
      .gte('created_at', sixtySecondsAgo)
      .limit(1)
      .maybeSingle();

    if (error) {
      if (import.meta.env.DEV) {
        console.error('Error checking duplicate payment:', error);
      }
      return { isDuplicate: false, error: error.message };
    }

    if (data) {
      return { isDuplicate: true, recentPayment: data as Payment, error: null };
    }

    return { isDuplicate: false, error: null };
  } catch (err: unknown) {
    const msg = err instanceof Error ? err.message : 'Failed to check duplicate payment';
    return { isDuplicate: false, error: msg };
  }
}

/**
 * Records a new payment.
 * Receipt number is generated by the Postgres trigger generate_receipt_number().
 */
export async function recordPayment(
  formData: RecordPaymentFormData
): Promise<{ payment: Payment | null; error: string | null }> {
  try {
    const { student_id, monthly_fee_id, amount, payment_date, method, notes } = formData;

    if (!amount || amount <= 0) {
      return { payment: null, error: 'Payment amount must be greater than ₹0' };
    }

    // Insert payment record into Supabase
    // Note: receipt_number is auto-generated by the database before insert trigger
    const { data, error } = await supabase
      .from('payments')
      .insert({
        student_id,
        monthly_fee_id,
        amount: Math.round(amount),
        payment_date,
        method,
        notes: notes?.trim() || null,
      })
      .select(`
        id,
        student_id,
        monthly_fee_id,
        amount,
        payment_date,
        method,
        receipt_number,
        notes,
        created_at,
        student:students(
          id,
          full_name,
          phone,
          email,
          guardian_name,
          guardian_phone
        ),
        monthly_fee:monthly_fees(
          id,
          billing_month,
          amount_due,
          due_date
        )
      `)
      .single();

    if (error) {
      if (import.meta.env.DEV) {
        console.error('Failed to record payment:', error);
      }
      return { payment: null, error: error.message };
    }

    const studentData = Array.isArray(data.student) ? data.student[0] : data.student;
    const feeData = Array.isArray(data.monthly_fee) ? data.monthly_fee[0] : data.monthly_fee;

    const payment: Payment = {
      id: data.id,
      student_id: data.student_id,
      monthly_fee_id: data.monthly_fee_id,
      amount: data.amount,
      payment_date: data.payment_date,
      method: data.method,
      receipt_number: data.receipt_number,
      notes: data.notes,
      created_at: data.created_at,
      student: studentData || null,
      monthly_fee: feeData || null,
    };

    return { payment, error: null };
  } catch (err: unknown) {
    const msg = err instanceof Error ? err.message : 'Failed to record payment';
    return { payment: null, error: msg };
  }
}

/**
 * Fetches payments history with joined student and monthly fee information.
 */
export async function getPaymentHistory(
  options?: PaymentHistoryFilterOptions
): Promise<{ payments: Payment[]; error: string | null }> {
  try {
    let query = supabase
      .from('payments')
      .select(`
        id,
        student_id,
        monthly_fee_id,
        amount,
        payment_date,
        method,
        receipt_number,
        notes,
        created_at,
        student:students(
          id,
          full_name,
          phone,
          email,
          guardian_name,
          guardian_phone,
          batch_id,
          batch:batches(id, name)
        ),
        monthly_fee:monthly_fees(
          id,
          billing_month,
          amount_due,
          due_date
        )
      `)
      .order('payment_date', { ascending: false })
      .order('created_at', { ascending: false });

    if (options?.studentId) {
      query = query.eq('student_id', options.studentId);
    }

    if (options?.method && options.method !== ('all' as any)) {
      query = query.eq('method', options.method);
    }

    if (options?.startDate) {
      query = query.gte('payment_date', options.startDate);
    }

    if (options?.endDate) {
      query = query.lte('payment_date', options.endDate);
    }

    if (options?.limit) {
      query = query.limit(options.limit);
    }

    const { data, error } = await query;

    if (error) {
      if (import.meta.env.DEV) {
        console.error('Failed to fetch payment history:', error);
      }
      return { payments: [], error: error.message };
    }

    if (!data) {
      return { payments: [], error: null };
    }

    let payments: Payment[] = data.map((row: any) => {
      const studentData = Array.isArray(row.student) ? row.student[0] : row.student;
      const feeData = Array.isArray(row.monthly_fee) ? row.monthly_fee[0] : row.monthly_fee;

      return {
        id: row.id,
        student_id: row.student_id,
        monthly_fee_id: row.monthly_fee_id,
        amount: row.amount,
        payment_date: row.payment_date,
        method: row.method,
        receipt_number: row.receipt_number,
        notes: row.notes,
        created_at: row.created_at,
        student: studentData || null,
        monthly_fee: feeData || null,
      };
    });

    // Batch filter (since batch is a nested relation)
    if (options?.batchId && options.batchId !== 'all') {
      payments = payments.filter((p: any) => p.student?.batch_id === options.batchId);
    }

    // Search filter
    if (options?.search && options.search.trim()) {
      const q = options.search.trim().toLowerCase();
      payments = payments.filter((p) => {
        const studentName = p.student?.full_name?.toLowerCase() || '';
        const guardianName = p.student?.guardian_name?.toLowerCase() || '';
        const receiptNo = p.receipt_number?.toLowerCase() || '';
        const notes = p.notes?.toLowerCase() || '';
        return (
          studentName.includes(q) ||
          guardianName.includes(q) ||
          receiptNo.includes(q) ||
          notes.includes(q)
        );
      });
    }

    return { payments, error: null };
  } catch (err: unknown) {
    const msg = err instanceof Error ? err.message : 'Failed to query payment history';
    return { payments: [], error: msg };
  }
}

/**
 * Fetches all fee records and payments for a specific student for the student profile view.
 */
export async function getStudentFeeSummary(
  studentId: string
): Promise<{ summary: StudentFeeSummary | null; error: string | null }> {
  try {
    // 1. Fetch monthly fees for this student
    const { data: feesData, error: feesError } = await supabase
      .from('monthly_fees')
      .select(`
        id,
        student_id,
        billing_month,
        amount_due,
        due_date,
        created_at,
        updated_at,
        payments(id, student_id, monthly_fee_id, amount, payment_date, method, receipt_number, notes, created_at)
      `)
      .eq('student_id', studentId)
      .order('billing_month', { ascending: false });

    if (feesError) {
      return { summary: null, error: feesError.message };
    }

    // 2. Fetch all payments for this student
    const { data: payData, error: payError } = await supabase
      .from('payments')
      .select(`
        id,
        student_id,
        monthly_fee_id,
        amount,
        payment_date,
        method,
        receipt_number,
        notes,
        created_at,
        monthly_fee:monthly_fees(id, billing_month, amount_due, due_date)
      `)
      .eq('student_id', studentId)
      .order('payment_date', { ascending: false })
      .order('created_at', { ascending: false });

    if (payError) {
      return { summary: null, error: payError.message };
    }

    const processedFees: MonthlyFee[] = (feesData || []).map((row: any) => {
      const payments: Payment[] = Array.isArray(row.payments) ? row.payments : [];
      const amountPaid = payments.reduce((acc, p) => acc + (p.amount || 0), 0);
      const balance = calculateFeeBalance(row.amount_due, amountPaid);
      const status = getFeeStatus(row.amount_due, amountPaid, row.due_date);
      const daysOverdue = calculateDaysOverdue(row.due_date);

      return {
        id: row.id,
        student_id: row.student_id,
        billing_month: row.billing_month,
        amount_due: row.amount_due,
        due_date: row.due_date,
        created_at: row.created_at,
        updated_at: row.updated_at,
        amount_paid: amountPaid,
        balance,
        status,
        days_overdue: daysOverdue,
        payments,
      };
    });

    const processedPayments: Payment[] = (payData || []).map((row: any) => ({
      id: row.id,
      student_id: row.student_id,
      monthly_fee_id: row.monthly_fee_id,
      amount: row.amount,
      payment_date: row.payment_date,
      method: row.method,
      receipt_number: row.receipt_number,
      notes: row.notes,
      created_at: row.created_at,
      monthly_fee: Array.isArray(row.monthly_fee) ? row.monthly_fee[0] : row.monthly_fee,
    }));

    let totalDue = 0;
    let totalPaid = 0;

    for (const f of processedFees) {
      totalDue += f.amount_due;
      totalPaid += f.amount_paid || 0;
    }

    const totalBalance = Math.max(0, totalDue - totalPaid);

    return {
      summary: {
        totalDue,
        totalPaid,
        totalBalance,
        fees: processedFees,
        payments: processedPayments,
      },
      error: null,
    };
  } catch (err: unknown) {
    const msg = err instanceof Error ? err.message : 'Failed to query student fee summary';
    return { summary: null, error: msg };
  }
}
